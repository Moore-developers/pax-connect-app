import Foundation

public enum ProductTextPresentation {
  /// Only fixed product labels participate in legacy compatibility; user names never enter this map.
  private static let legacyEventKeys: [String: String] = {
    var result: [String: String] = [:]
    for (key, value) in PresentationContext.chinese.messages.sorted(by: { $0.key < $1.key })
    where key.hasPrefix("event.") {
      if case .text(let original) = value, result[original] == nil { result[original] = key }
    }
    return result
  }()
  public static func text(
    _ meaning: ProductText?, original: String, context: PresentationContext
  ) -> String {
    guard let meaning, let message = context.messages[meaning.code] else { return original }
    let template: String
    switch message {
    case .text(let value): template = value
    case .plural(let one, let other):
      guard let count = meaning.params["count"].flatMap(Int.init) else { return original }
      template = context.language == .english && count == 1 ? one ?? other : other
    }
    var parameters = meaning.params
    if meaning.code == "client.protocolMismatch", parameters["daemon"] == "" {
      parameters["daemon"] = context.text("common.unknown")
    }
    return LanguageTemplate.render(template, parameters: parameters) ?? original
  }
  public static func staticEventLabel(
    _ meaning: ProductText?, original: String, context: PresentationContext
  ) -> String {
    if let meaning { return text(meaning, original: original, context: context) }
    guard let key = legacyEventKeys[original] else { return original }
    return context.text(key)
  }
  public static func eventName(_ event: SystemEvent, context: PresentationContext) -> String {
    staticEventLabel(event.nameText, original: event.name, context: context)
  }
  public static func recordTitle(_ record: LogRecord, context: PresentationContext) -> String {
    if let event = record.systemEvent {
      let name = eventName(event, context: context)
      let key = "event.result." + event.result
      guard context.messages[key] != nil else { return name }
      return name + (context.language == .chinese ? "：" : ": ") + context.text(key)
    }
    return text(record.titleText, original: record.title, context: context)
  }
  public static func category(_ record: LogRecord, context: PresentationContext) -> String {
    staticEventLabel(
      record.systemEvent?.category.nameText, original: record.categoryName, context: context)
  }
  public static func logTitle(_ log: ProductLog, context: PresentationContext) -> String {
    // These fixed titles are generated by the daemon's problem reducer.
    // Keep custom and upstream messages, even when they share a problem category.
    if !log.problemID.isEmpty {
      switch (log.category, log.message) {
      case ("blocked", "策略阻断"): return context.text("dashboard.problem_blocked")
      case ("unconfirmed", "当前通道待确认"): return context.text("dashboard.problem_unconfirmed")
      case ("warning", "诊断警告"): return context.text("dashboard.problem_warning")
      case (_, "连接或操作失败 · 原因未分类"):
        return context.text("dashboard.problem_uncategorized")
      default: break
      }
    }
    if let event = log.systemEvent {
      var record = LogRecord()
      record.systemEvent = event
      return recordTitle(record, context: context)
    }
    return text(log.messageText, original: log.message, context: context)
  }
}
