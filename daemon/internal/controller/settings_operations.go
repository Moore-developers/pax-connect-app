package controller

import (
	"context"
	"strconv"
	"time"

	"google.golang.org/genproto/googleapis/rpc/errdetails"
	"google.golang.org/grpc/codes"
	"google.golang.org/grpc/status"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/types/known/timestamppb"
	pb "pax-connect/daemon/gen/proto/paxv1"
	"pax-connect/daemon/internal/config"
)

// Settings use the existing configuration queue and the original storage owners.
// Caller disconnects only stop waiting; admitted commits retain their request result.
func (c *Controller) startSetting(ctx context.Context, kind string, req proto.Message, identity *pb.OperationContext) (*pb.OperationAck, error) {
	req = proto.Clone(req)
	// These legacy App fields are generated by the daemon for contextual requests.
	switch q := req.(type) {
	case *pb.ClearLogsRequest:
		if q.OperationId != "" || q.RequestedAt != nil {
			return nil, status.Error(codes.InvalidArgument, "request_invalid")
		}
	case *pb.UpdateSettingsRequest:
		if q.OperationId != "" || q.RequestedAt != nil {
			return nil, status.Error(codes.InvalidArgument, "request_invalid")
		}
	}
	return c.contextRequest(ctx, kind, req, identity, func() (*pb.OperationAck, error) {
		result := &pb.SettingsOperationResult{}
		acceptedAt := timestamppb.Now()
		var id string
		ready := make(chan struct{})
		label := map[string]string{"settings.privacy": "保存网络保护", "settings.measurement": "保存线路测量", "settings.logs_retention": "修改日志保留期", "settings.logs_clear": "清除日志历史"}[kind]
		op := &routeOperation{label: label, settingsResult: result, evidence: &config.SystemEvent{Type: kind, Name: label, Category: config.EventCategory{Key: "settings", Name: "设置与数据", Symbol: "gearshape"}}}
		op.apply = func(task context.Context) error {
			<-ready
			if task.Err() != nil {
				return task.Err()
			}
			// Once the local transaction begins it is not cancellable by a Stop or RPC timeout.
			commit, cancel := context.WithTimeout(context.WithoutCancel(task), 30*time.Second)
			defer cancel()
			var err error
			switch q := req.(type) {
			case *pb.NetworkPrivacy:
				q.Context = nil
				value, e := c.saveNetworkPrivacy(commit, q)
				err = e
				if e == nil {
					result.Value = &pb.SettingsOperationResult_Privacy{Privacy: value}
				}
			case *pb.MeasurementPreferences:
				q.Context = nil
				value, e := c.SaveMeasurementPreferences(commit, q)
				err = e
				if e == nil {
					result.Value = &pb.SettingsOperationResult_Measurement{Measurement: value}
				}
			case *pb.ClearLogsRequest:
				q.Context, q.OperationId, q.RequestedAt = nil, id, acceptedAt
				_, err = c.clearLogs(commit, q, result)
			case *pb.UpdateSettingsRequest:
				q.Context, q.OperationId, q.RequestedAt = nil, id, acceptedAt
				_, err = c.updateLogSettings(commit, q, result)
			}
			if err == nil {
				return nil
			}
			code := status.Convert(err).Message()
			params := []string{}
			switch code {
			case "network_privacy_conflict":
				params = append(params, strconv.FormatUint(c.privacy.value.Revision, 10))
			case "measurement_preferences_stale":
				c.preferences.mu.Lock()
				params = append(params, strconv.FormatUint(c.preferences.value.Revision, 10))
				c.preferences.mu.Unlock()
			case "settings_conflict":
				code = "settings_stale"
				c.mu.Lock()
				params = append(params, strconv.FormatUint(c.current.GetSettings().GetRevision(), 10))
				c.mu.Unlock()
			}
			return &productError{code: code, params: params}
		}
		ack, err := c.admitRouteOperation(ctx, op)
		if err != nil {
			return nil, err
		}
		id = ack.OperationId
		close(ready)
		return ack, nil
	})
}

func (c *Controller) trackedSetting(ctx context.Context, kind string, req proto.Message, identity *pb.OperationContext) (*pb.SettingsOperationResult, error) {
	ack, err := c.startSetting(ctx, kind, req, identity)
	if err != nil {
		return nil, err
	}
	// The barrier also works when a same-request retry finds an admitted operation.
	if err := c.query(ctx, func(context.Context) {}); err != nil {
		return nil, err
	}
	op, err := c.GetOperation(ctx, &pb.GetOperationRequest{DaemonInstance: c.instance, Identity: &pb.GetOperationRequest_OperationId{OperationId: ack.OperationId}})
	if err != nil {
		return nil, err
	}
	if op.Error != nil {
		st := status.New(codes.FailedPrecondition, op.Error.Code)
		if len(op.Error.MessageParams) > 0 {
			detailed, e := st.WithDetails(&errdetails.ErrorInfo{Reason: op.Error.Code, Metadata: map[string]string{"latest_revision": op.Error.MessageParams[0]}})
			if e == nil {
				st = detailed
			}
		}
		return nil, st.Err()
	}
	if op.GetSettings() == nil {
		return nil, status.Error(codes.Unavailable, "settings_commit_uncertain")
	}
	return op.GetSettings(), nil
}
