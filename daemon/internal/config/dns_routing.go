package config

// CompileDNSRouting projects traffic rules onto predicates available before lookup.
// The first undecidable user rule keeps the query on the shared proxy resolver.
func CompileDNSRouting(library RoutingLibrary, apps []RoutingApplication, routesByID map[string]string, mode string) ([]map[string]any, error) {
	if mode == "" {
		mode = "balanced"
	}
	if mode != "balanced" && mode != "strict" {
		return nil, ErrRoutingLibrary
	}
	result := []map[string]any{}
	// A user rule whose predicate is not known before lookup may win over
	// every later rule. Keep that uncertainty instead of exposing a lower
	// domestic/selected resolver as though its priority were already decided.
	compiled, err := compileRouting(library, apps, routesByID, true)
	if err != nil {
		return nil, err
	}
	guardedUnknownSource := false
	for _, item := range compiled {
		rule := item.rule
		match, needsProcess := dnsQueryMatch(rule)
		if match == nil {
			if item.user {
				result = append(result, map[string]any{"server": "dns-remote"})
				break
			}
			continue
		}
		if needsProcess && !guardedUnknownSource {
			result = append(result, sharedDNSFallback())
			guardedUnknownSource = true
		}
		outbound, _ := rule["outbound"].(string)
		method := item.evidence.Method
		processRule := needsProcess && (method == "application" || method == "process" || method == "source")
		switch {
		case item.evidence.UnavailableRoute != "":
			match["action"] = "reject"
			match["no_drop"] = true
		case processRule && (outbound == "direct" || rule["action"] == "reject"):
			// Keep the existing resolver for non-fixed process rules that win.
			match["server"] = "dns-remote"
		case rule["action"] == "reject":
			match["action"] = "reject"
		case outbound == "direct" && mode == "balanced":
			match["server"] = "dns-domestic"
		case outbound == "direct" || outbound == "proxy":
			match["server"] = "dns-remote"
		case outbound != "":
			match["server"] = outbound
		default:
			continue
		}
		result = append(result, match)
	}
	return result, nil
}

// A missing path or the system resolver's path cannot settle a process rule,
// including a negative condition generated by a preceding follow-default rule.
func sharedDNSFallback() map[string]any {
	return map[string]any{
		"type": "logical", "mode": "or", "server": "dns-remote",
		"rules": []any{
			map[string]any{"process_path_regex": []string{"^/"}, "invert": true},
			map[string]any{"process_path": []string{"/usr/sbin/mDNSResponder", "/usr/sbin/mDNSResponderHelper"}},
		},
	}
}

// Keep the whole predicate, or none of it when part depends on the answer or
// other unavailable metadata. The caller handles unknown process identity.
func dnsQueryMatch(rule map[string]any) (map[string]any, bool) {
	match := map[string]any{}
	needsProcess := false
	for key, value := range rule {
		switch key {
		case "action", "outbound", "no_drop":
		case "domain", "domain_suffix", "domain_keyword", "domain_regex", "type", "mode", "invert":
			match[key] = value
		case "process_name", "process_path", "process_path_regex":
			match[key] = value
			needsProcess = true
		case "rule_set":
			// Built-in GeoSite is domain-only. Other sets can depend on resolved IPs.
			valid := false
			switch tags := value.(type) {
			case []string:
				valid = len(tags) == 1 && (tags[0] == "geosite-cn" || tags[0] == "geosite-google")
			case []any:
				valid = len(tags) == 1 && (tags[0] == "geosite-cn" || tags[0] == "geosite-google")
			}
			if !valid {
				return nil, false
			}
			match[key] = value
		case "rules":
			children, ok := value.([]any)
			if !ok {
				return nil, false
			}
			converted := []any{}
			for _, child := range children {
				v, ok := child.(map[string]any)
				if !ok {
					return nil, false
				}
				predicate, process := dnsQueryMatch(v)
				if predicate == nil {
					return nil, false
				}
				converted = append(converted, predicate)
				needsProcess = needsProcess || process
			}
			match[key] = converted
		default:
			return nil, false
		}
	}
	if len(match) == 0 {
		return nil, false
	}
	return match, needsProcess
}

// DNSRoutingRules is the shared complete query policy for activation and hot edits.
func DNSRoutingRules(l RoutingLibrary, apps []RoutingApplication, tags map[string]string, mode string) ([]map[string]any, error) {
	rules, err := CompileDNSRouting(l, apps, tags, mode)
	if err != nil {
		return nil, err
	}
	return append([]map[string]any{{"domain_suffix": []string{"local", "lan", "home.arpa"}, "server": "dns-intranet"}}, rules...), nil
}
